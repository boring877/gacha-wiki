/**
 * Compute status from dates relative to now (UTC).
 */
function computeStatus(banner) {
  const now = Date.now();
  const start = new Date(banner.startDate).getTime();
  const end = new Date(banner.endDate).getTime();
  if (now < start) return 'upcoming';
  if (now >= start && now <= end) return 'current';
  return 'ended';
}

jpBannerTimelineData.forEach(banner => {
  banner.status = computeStatus(banner);
});

/**
 * Get all JP banners sorted by start date (newest first).
 */
export function getAllJpBanners() {
  return jpBannerTimelineData.sort((a, b) => new Date(b.startDate) - new Date(a.startDate));
}

/**
 * Get JP banners for a given year (newest first).
 */
export function getJpBannersByYear(year) {
  return jpBannerTimelineData
    .filter(b => b.year === year)
    .sort((a, b) => new Date(b.startDate) - new Date(a.startDate));
}

/**
 * Get banner by ID.
 */
export function getJpBannerById(id) {
  return jpBannerTimelineData.find(b => b.id === id);
}

/**
 * Years covered, newest first.
 */
export function getJpTimelineYears() {
  return [...new Set(jpBannerTimelineData.map(b => b.year))].sort((a, b) => b - a);
}
